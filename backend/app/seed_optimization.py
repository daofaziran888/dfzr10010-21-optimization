"""表优化执行计划相关的示例数据。

把原来的“按登记顺序抢预算”的示例任务补全为可计算的文件数、容量、预算与收益，
并给出一份已经发布的历史批次，方便直接看到效果统计与统计报告的完整链路。
"""
from __future__ import annotations

from typing import Any


def _task(
    entry_id: int,
    code: str,
    table: str,
    kind: str,
    params: str,
    files: int,
    capacity: float,
    budget: float,
    benefit: float,
    after_files: int,
    after_capacity: float,
    order: int,
    status: str = "待执行",
    plan: str = "",
    effect: str = "",
) -> dict[str, Any]:
    return {
        "id": entry_id,
        "status": status,
        "pending": status in ("待执行", "执行中"),
        "abnormal": False,
        "任务编号": code,
        "表名称": table,
        "优化类型": kind,
        "优化参数": params,
        "执行计划": plan,
        "资源消耗": f"{budget:g}GB",
        "优化效果": effect,
        "任务状态": status,
        "文件数": files,
        "容量GB": capacity,
        "预算需求GB": budget,
        "预计收益GB": benefit,
        "优化后文件数": after_files,
        "优化后容量GB": after_capacity,
        "登记顺序": order,
        "收益分": round(benefit / budget, 4) if budget else 0.0,
        "计划版本": 0,
        "批次编号": plan,
        "实际文件数": 0,
        "实际容量GB": 0.0,
    }


